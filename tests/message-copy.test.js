const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const { parseHTML } = require('linkedom');
const moduleSource = fs.readFileSync(require.resolve('../src/renderer/message-copy.js'), 'utf8');
const { document } = parseHTML('<html><body><button></button><div class="message-content"><div class="search-answer"><p>First paragraph.</p><div><p>Nested paragraph.</p></div><p>Final paragraph.</p></div><div class="message-actions"><button>Copy</button></div></div></body></html>');
const copied = [], timers = new Map(); let nextTimer = 0, fail = false, errors = 0;
const root = { ultronAPI: { copyText: async text => { if (fail) return { success: false, error: 'Clipboard unavailable' }; copied.push(text); return { success: true }; } } };
vm.runInNewContext(moduleSource, { window: root, setTimeout: callback => { timers.set(++nextTimer, callback); return nextTimer; }, clearTimeout: id => timers.delete(id) });
const copy = root.BrownMessageCopy;
const button = document.querySelector('button');
const click = () => button.onclick({ stopPropagation() {} });
(async () => {
  const original = '# Full answer\n\n```html\n<div>Hello</div>\n```\n\n' + 'Long message content. '.repeat(15000) + '\nFinal sentence.';
  assert.equal(copy.contentText(original, null, true), original, 'code, Markdown and the entire long response are preserved');
  assert.equal(copy.contentText('<hello> literal user text', null, false), '<hello> literal user text');
  const rich = copy.contentText('<div class="search-answer">...</div>', document.querySelector('.message-content'));
  assert(rich.includes('Nested paragraph.') && rich.includes('Final paragraph.'));
  assert(!rich.includes('Copy'));
  copy.bind(button, () => 'Thinking');
  copy.bind(button, () => original, { onError: () => errors++ });
  await click();
  assert.deepEqual(copied, [original], 'rebinding uses only the final message, with one clipboard write');
  assert(button.classList.contains('is-copied')); assert.equal(button.getAttribute('aria-label'), 'Copied');
  assert(button.innerHTML.includes('m5 12 4 4 10-10'), 'copy icon becomes a tick');
  await click(); assert.equal(timers.size, 1, 'repeated clicks restart a single confirmation timer');
  [...timers.values()][0]();
  assert(!button.classList.contains('is-copied')); assert.equal(button.getAttribute('aria-label'), 'Copy message');
  assert(button.innerHTML.includes('<rect'));
  fail = true; await click();
  assert(!button.classList.contains('is-copied'), 'failure never shows success'); assert.equal(errors, 1);
  assert.match(button.title, /failed/);
  const renderer = fs.readFileSync(require.resolve('../src/renderer/renderer.js'), 'utf8');
  const chatActions = renderer.slice(renderer.indexOf("btnCopy.className = 'btn-copy-msg"), renderer.indexOf("btnCopyUser.addEventListener('mouseenter'"));
  assert(!chatActions.includes("btnCopy.addEventListener('click'"));
  assert(!renderer.includes("btnCopyUser.addEventListener('click'"));
  const ipcSource = fs.readFileSync(require.resolve('../src/main/ipc.js'), 'utf8');
  const handlers = new Map(); let nativeText = '';
  const context = vm.createContext({ ipcMain: { handle: (name, handler) => handlers.set(name, handler) }, clipboard: { writeText: text => { nativeText = text; } } });
  const start = ipcSource.indexOf('function registerClipboardIpcHandlers(');
  vm.runInContext(ipcSource.slice(start, ipcSource.indexOf('function registerVisualIpcHandlers', start)), context);
  context.registerClipboardIpcHandlers(); context.registerClipboardIpcHandlers();
  assert.equal(handlers.size, 1);
  assert(handlers.get('clipboard:write-text')({}, original).success); assert.equal(nativeText, original);
  assert.equal(handlers.get('clipboard:write-text')({}, {}).success, false);
  console.log('PASS: full AI/user copying, intact code, current response binding, success tick/reset, failures and native clipboard bridge.');
})().catch(error => { console.error(error); process.exitCode = 1; });
