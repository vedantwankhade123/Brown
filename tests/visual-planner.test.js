const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const planner = require('../src/renderer/visual-planner');
const example = family => JSON.parse(planner.instructions({ family }).split('\n').at(-1));
const copy = value => JSON.parse(JSON.stringify(value));
async function run() {
  assert.equal(planner.plan('draw a compiler pipeline diagram').family, 'flowchart');
  assert.equal(planner.plan('draw a sequence diagram for login').family, 'sequence');
  assert.equal(planner.plan('create a system architecture diagram').family, 'architecture');
  assert.equal(planner.plan('draw architecture with request-response interactions').family, 'architecture');
  assert.equal(planner.plan('graph revenue over time').family, 'chart');
  assert.equal(planner.plan('draw an ER diagram').family, 'artifact');
  assert.equal(planner.plan('create a swimlane diagram').layout, 'swimlane');
  const flow = example('flowchart'), sequence = example('sequence'), architecture = example('architecture'), chart = example('chart');
  for (const spec of [flow, sequence, architecture]) assert.deepEqual(planner.validate(spec, { family: spec.family }), []);
  assert.deepEqual(planner.validate(chart, { family: 'chart', type: 'bar' }, 'Alpha: 10; Beta: 20'), []);
  assert.match(planner.compile(flow), /flowchart TD/);
  assert.match(planner.compile(sequence), /sequenceDiagram/);
  assert.match(planner.compile(sequence), /p_api-->>p_client/);
  assert.match(planner.compile(architecture), /subgraph g_frontend/);
  assert.match(planner.compile(chart), /```chart/);
  assert(!planner.compile(chart).includes('evidence'), 'evidence stays internal');
  assert(planner.validate(sequence, { family: 'architecture' }).length);
  assert(planner.validate(sequence, { family: 'sequence' }, 'Browser sends login to API. Database replies valid.').some(error => /participant Browser/.test(error)));
  let repeated = copy(sequence); repeated.messages.push(copy(repeated.messages[0]));
  assert(planner.validate(repeated, { family: 'sequence' }).some(error => /repeated/.test(error)));
  let invalid = copy(flow); invalid.edges[0].to = 'missing';
  assert(planner.validate(invalid, { family: 'flowchart' }).some(error => /existing IDs/.test(error)));
  invalid = copy(flow); invalid.edges = invalid.edges.filter(edge => edge.to !== 'reject');
  assert(planner.validate(invalid, { family: 'flowchart' }).some(error => /two labeled/.test(error)));
  invalid = copy(architecture); invalid.nodes[0].group = 'unknown';
  assert(planner.validate(invalid, { family: 'architecture' }).length);
  invalid = copy(flow); invalid.layout = 'tree'; invalid.edges.push({ from: 'done', to: 'start' });
  assert(planner.validate(invalid, { family: 'flowchart' }).some(error => /tree needs/.test(error)));
  invalid = copy(chart); invalid.data[0].value = 100;
  assert(planner.validate(invalid, { family: 'chart' }, 'Alpha: 10; Beta: 20').some(error => /evidence/.test(error)));
  invalid = copy(chart); invalid.type = 'pie'; invalid.data[0].value = -10; invalid.data[0].evidence = 'Alpha: -10';
  assert(planner.validate(invalid, { family: 'chart' }, 'Alpha: -10; Beta: 20').some(error => /positive total/.test(error)));
  let calls = 0;
  const generated = await planner.generate({ request: 'draw a sequence diagram', generate: async (_system, user, schema) => {
    assert.equal(schema.properties.family.const, 'sequence');
    calls++;
    if (calls === 1) return JSON.stringify(flow);
    assert.match(user, /Expected sequence/);
    return JSON.stringify(sequence);
  } });
  assert.equal(calls, 2); assert.match(generated, /sequenceDiagram/);
  const explicitReply = copy(sequence); explicitReply.messages[1].reply = false; explicitReply.messages[1].label = 'Send session token';
  const replyAnswer = await planner.generate({ request: 'Draw a sequence diagram. API replies session to Client.', generate: async () => JSON.stringify(explicitReply) });
  assert.match(replyAnswer, /p_api-->>p_client: Send session token/, 'explicit source response is rendered as a reply without another model call');
  calls = 0;
  const failed = await planner.generate({ request: 'draw a flowchart', generate: async () => { calls++; return '{bad'; } });
  assert.equal(calls, 3); assert.match(failed, /two repair attempts/);
  calls = 0;
  const unrenderable = await planner.generate({ request: 'draw a sequence diagram', generate: async () => { calls++; return JSON.stringify(sequence); }, verify: async () => { throw Error('Node overlap'); } });
  assert.equal(calls, 3); assert.match(unrenderable, /Node overlap/);
  calls = 0;
  const missing = await planner.generate({ request: 'draw a sales chart', generate: async () => { calls++; } });
  assert.equal(calls, 0); assert.match(missing, /provide.*numeric values/);
  const unsupported = await planner.generate({ request: 'draw a histogram', generate: async () => { throw Error('must not substitute'); } });
  assert.match(unsupported, /cannot preserve/);
  const controller = new AbortController(); controller.abort();
  await assert.rejects(planner.generate({ request: 'draw a diagram', signal: controller.signal, generate: async () => '{}' }), /Cancelled/);
  const renderer = fs.readFileSync(require.resolve('../src/renderer/renderer.js'), 'utf8');
  const context = vm.createContext({ isReminderOrTimerRequest: () => false, hasDesktopActionCues: () => false });
  const start = renderer.indexOf('function isVisualCreationRequest(');
  vm.runInContext(renderer.slice(start, renderer.indexOf('\nfunction classifyIntent(', start)), context);
  assert(context.isVisualCreationRequest('Can you draw a sequence diagram?'));
  assert(context.isVisualCreationRequest('Explain the compiler with a diagram'));
  assert(!context.isVisualCreationRequest('What is a sequence diagram?'));
  assert(!renderer.includes('The first line inside the block must be "flowchart TD"'));
  const scatterPrompt='Create a scatter plot with Study hours on the x-axis and Score on the y-axis. Use these pairs: (1,40), (2,50), (3,55), (4,70), (5,75), (6,85). Do not invent additional observations.';
  const stackedPrompt='Create a stacked bar chart of quarterly device sales. Q1: Phones 40, Laptops 20. Q2: Phones 50, Laptops 30. Q3: Phones 45, Laptops 35. Include a legend and label the axis Units sold.';
  const chartJson = answer=>JSON.parse(answer.match(/```chart\n([\s\S]*?)```/)[1]);
  const noModel=async()=>{throw Error('Supplied data must not require model extraction');};
  const scatterAnswer=await planner.generate({request:scatterPrompt,generate:noModel});const scatterData=chartJson(scatterAnswer);
  assert.equal(scatterData.type,'scatter');assert.deepEqual(scatterData.points,[[1,40],[2,50],[3,55],[4,70],[5,75],[6,85]]);assert.equal(scatterData.xLabel,'Study hours');assert.equal(scatterData.yLabel,'Score');
  const stackedAnswer=await planner.generate({request:stackedPrompt,generate:noModel});const stackedData=chartJson(stackedAnswer);
  assert.equal(stackedData.type,'stacked-bar');assert.deepEqual(stackedData.labels,['Q1','Q2','Q3']);assert.deepEqual(stackedData.series,[{name:'Phones',values:[40,50,45]},{name:'Laptops',values:[20,30,35]}]);
  assert.equal(stackedData.yLabel,'Units sold');
  const visualContext={window:{},document:{readyState:'loading',addEventListener(){}},console};vm.runInNewContext(fs.readFileSync(require.resolve('../src/renderer/visual-engine.js'),'utf8'),visualContext);
  for(const data of [scatterData,stackedData]) {
    const html=visualContext.window.UltronVisualEngine.renderChart(JSON.stringify(data));assert.match(html,/<svg/);assert(!html.includes('could not be rendered'));
  }
  assert.match(visualContext.window.UltronVisualEngine.renderChart(JSON.stringify(scatterData)),/Study hours/);
  const resolved=planner.resolveRequest('take random on your own',[{text:stackedPrompt,isAi:false},{text:'Please provide data.',isAi:true}]);
  assert.equal(planner.resolveRequest(resolved,[{text:stackedPrompt,isAi:false}]),resolved,'follow-up resolution is idempotent');
  assert.deepEqual(chartJson(await planner.generate({request:resolved,generate:noModel})).series,stackedData.series,'follow-up preserves already supplied measurements');
  const sampleRequest=planner.resolveRequest('use sample data',[{isAi:false,text:'Create a scatter plot comparing study hours and scores.'}]);
  const sampleAnswer=await planner.generate({request:sampleRequest,generate:noModel});assert.match(sampleAnswer,/Illustrative sample/);assert.match(sampleAnswer,/not real measurements/);
  const browserSpec={family:'sequence',title:'Webpage loading',participants:[{id:'browser',label:'Browser'},{id:'dns',label:'DNS Server'},{id:'web',label:'Web Server'}],messages:[{from:'browser',to:'dns',label:'Resolve hostname'},{from:'dns',to:'browser',label:'Return IP address',reply:true},{from:'browser',to:'web',label:'Request webpage'},{from:'web',to:'browser',label:'Return response',reply:true}]};
  const combined=await planner.generate({request:'Explain how a browser loads a webpage. First show a sequence diagram involving Browser, DNS Server, and Web Server. Then show a table explaining each message in the diagram.',generate:async()=>JSON.stringify(browserSpec)});
  assert.match(combined,/```mermaid\nsequenceDiagram/);assert.match(combined,/\| Message \| Sender \| Receiver \|/);assert.equal((combined.match(/^\| /gm)||[]).length,browserSpec.messages.length+2);
  assert(context.isVisualCreationRequest('Explain how a browser loads a webpage. First show a sequence diagram involving Browser, DNS Server, and Web Server. Then show a table explaining each message in the diagram.'));
  console.log('PASS: family routing, structured compilation, relationships, supplied chart evidence, bounded repair and cancellation.');
}
if (require.main === module) run().catch(error => { console.error(error); process.exitCode = 1; });
module.exports = { run, example };
