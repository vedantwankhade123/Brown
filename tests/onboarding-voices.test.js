const assert = require('node:assert/strict');
const { parseHTML } = require('linkedom');
const { mount, voices, downloadAfterSetup } = require('../src/renderer/onboarding-voices');
async function run() {
  const { document, window } = parseHTML('<html><body><div id="onboarding-screen"><div id="picker"></div></div><button id="outside">Outside</button></body></html>');
  const root = document.getElementById('picker');
  const saved = new Map(), activations = [], downloads = [];
  const storage = { setItem: (key, value) => saved.set(key, value), getItem: key => saved.get(key), removeItem: key => saved.delete(key) };
  const api = { setActiveTtsModel: async key => { activations.push(key); return { success: true }; }, downloadKokoroOnboardingVoices: async ids => { downloads.push(ids); return { success: true }; } };
  const picker = mount(root, { window: { innerHeight: 667, matchMedia: () => ({ matches: true }) }, storage, api,
    onChange: voice => storage.setItem('ultron-onboarding-voice-choice', JSON.stringify({ ...voice, enabled: true })) });
  root.querySelectorAll('button').forEach(button => { button.focus = () => {}; button.getBoundingClientRect = () => ({ bottom: 300 }); });
  const flush = async () => { for (let i = 0; i < 12; i++) await Promise.resolve(); };
  const trigger = root.querySelector('.onboard-voice-trigger');
  assert.equal(picker.selected().key, 'kokoro-heart');
  trigger.click(); assert.equal(trigger.getAttribute('aria-expanded'), 'true');
  assert(document.getElementById('onboarding-screen').classList.contains('onboard-voice-choosing'));
  assert.equal(root.querySelectorAll('[data-voice-preview]').length, 0);
  root.querySelector('[data-voice-select="kokoro-michael"]').click(); await flush();
  assert.equal(picker.selected().name, 'Michael');
  assert.equal(trigger.getAttribute('aria-expanded'), 'false');
  assert.equal(root.querySelectorAll('[aria-checked="true"]').length, 1);
  assert.equal(root.querySelectorAll('[aria-pressed="true"]').length, 1);
  assert.equal(JSON.parse(saved.get('ultron-onboarding-voice-choice')).key, 'kokoro-michael');
  assert.deepEqual(downloads, []); assert.deepEqual(activations, []);
  trigger.click();
  root.querySelector('.onboard-voice-close').click(); assert.equal(trigger.getAttribute('aria-expanded'), 'false');
  picker.setBusy(true); assert([...root.querySelectorAll('button')].every(button => button.disabled));
  picker.setBusy(false); trigger.click();
  root.dispatchEvent(Object.assign(new window.Event('keydown'), { key: 'Escape' }));
  assert.equal(trigger.getAttribute('aria-expanded'), 'false');
  trigger.click(); document.getElementById('outside').dispatchEvent(new window.Event('pointerdown', { bubbles: true }));
  assert.equal(trigger.getAttribute('aria-expanded'), 'false');
  picker.destroy();
  const restored = mount(root, { window: {}, storage });
  assert.equal(restored.selected().key, 'kokoro-michael'); restored.destroy();
  const choice = { ...voices[1], enabled: true };
  const first = downloadAfterSetup(choice, { api, storage });
  assert.equal(first, downloadAfterSetup(choice, { api, storage }));
  assert(saved.has('ultron-pending-voice-setup'));
  await first;
  assert.deepEqual(downloads, [['am_michael']]);
  assert.deepEqual(activations, ['kokoro-michael']);
  assert.equal(saved.get('ultron-tts-neural-model'), 'kokoro-michael');
  assert(!saved.has('ultron-pending-voice-setup'));
  await downloadAfterSetup({ ...choice, enabled: false }, { api, storage });
  assert.equal(downloads.length, 1);
  await assert.rejects(downloadAfterSetup(choice, { api: { downloadKokoroOnboardingVoices: async () => ({ success: false, error: 'Offline' }) }, storage }), /Offline/);
  assert.equal(activations.length, 1);
  console.log('PASS: persisted voice selection, replacement chooser, no early downloads, deferred single background setup, opt-out and failures');
}
module.exports = { run };
if (require.main === module) run().catch(error => { console.error(error); process.exitCode = 1; });
